def _upstream(name):
    """One vendored upstream module loaded on its own (json_parser and prompts
    use only the standard library), so the test process never imports the
    claudecode package or anthropic."""
    spec = importlib.util.spec_from_file_location(f"ccsr_{name}", CCSR_DIR / "claudecode" / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    previous, sys.dont_write_bytecode = sys.dont_write_bytecode, True   # keep the vendored copy unchanged
    try:
        spec.loader.exec_module(module)
    finally:
        sys.dont_write_bytecode = previous
    return module


