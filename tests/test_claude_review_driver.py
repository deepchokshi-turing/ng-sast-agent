# ---------------------------------------------------------------- whole runs


def _ok_script(findings=None, files_reviewed=3):
    return [{"exit": 0, "wrapper": wrapper(review(findings or [], files_reviewed))}]


def _assert_key_only_in_the_key_file(run, result):
    text = run.out.read_text()
    assert KEY not in text and KEY not in result.stdout and KEY not in result.stderr
    for call in run.claude_calls():
        assert KEY not in json.dumps(call["argv"]) and not call["env_has_key"]


def test_whole_run_stock_mode(tmp_path, repo, net):
    findings = [finding("src/app/tools.py", 5), finding("src/app/llm.py", 2, category="sensitive_data_logging",
                                                        severity="MEDIUM"),
                finding("src/app/tools.py", 1, category="denial_of_service", description="denial of service")]
    run = DriverRun(tmp_path / "run", repo, IN_SCOPE, script=_ok_script(findings), net_url=net,
                    anthropic={"exclude_categories": ["sensitive_data_logging"]})
    result = run.run()
    doc = run.document()
    assert result.returncode == 0, (result.stdout, result.stderr, doc.get("error"))
    assert doc["status"] == "ok" and result.stdout.strip().splitlines()[-1].startswith("DRIVER_RESULT ")
    # The upstream hard rule drops the DoS finding, the filter the logging one.
    assert [(f["file"], f["line"]) for f in doc["kept"]] == [("src/app/tools.py", 5)]
    assert doc["kept"][0]["_filter_metadata"]["confidence_score"] == 8
    stages = sorted(e["filter_stage"] for e in doc["excluded"])
    assert stages == ["claude_api", "hard_rules"]
    assert doc["filter"]["mode"] == "claude" and doc["filter"]["summary"]["total_findings"] == 3
    assert doc["pr"]["in_diff"] == ["src/app/empty.py", "src/app/llm.py", "src/app/tools.py"]
    assert doc["claude_code_version"] == "2.1.296 (Claude Code)"
    assert doc["versions"]["anthropic"] == "0.79.0-fake"
    assert doc["upstream_default_model"] == "claude-opus-4-1-20250805"
    assert doc["cli"]["cli"]["total_cost_usd"] == 0.42 and len(doc["cli"]["attempts"]) == 1
    assert sorted(doc["environment_removed"]) == ["ANTHROPIC_BASE_URL", "CLAUDE_CODE_PROVIDER_MANAGED_BY_HOST",
                                                  "CLAUDE_CODE_USE_BEDROCK"]

    (call,) = run.claude_calls()
    settings_path = call["argv"][call["argv"].index("--settings") + 1]
    assert call["argv"][1:] == driver.cli_argv("x", "claude-opus-4-1-20250805", settings_path)[1:]
    assert call["cwd"] == str(repo) and call["home"] == run.request["home"]
    assert call["helper_key"] == KEY            # the apiKeyHelper reads the key file
    assert call["settings_mode"] == "0o600" and call["settings"] == doc["cli_settings"]
    assert "ANTHROPIC_BASE_URL" not in call["env_names"] and "CLAUDE_CODE_USE_BEDROCK" not in call["env_names"]
    # The CLI sees only the allow-listed names plus its own switches, so no host Claude setting
    # (CLAUDE_CODE_PROVIDER_MANAGED_BY_HOST, CLAUDE_MODEL, PYTHONPATH of the driver) reaches it.
    names = {n for n in call["env_names"] if not n.startswith("LC_")}   # Python may add LC_CTYPE
    assert names <= (set(driver.CLI_ENV_ALLOW) | set(driver.QUIET_ENV) | {"HOME", "PWD", "SHLVL", "_"})
    assert "CLAUDE_CODE_PROVIDER_MANAGED_BY_HOST" not in names and "PYTHONPATH" not in names
    assert {n for n in doc["cli_environment"] if not n.startswith("LC_")} == names - {"PWD", "SHLVL", "_"}
    assert call["prompt_has_diff"] and "Full repository security review" in call["prompt"]
    assert stat.S_IMODE(os.stat(os.path.dirname(settings_path)).st_mode) == 0o700
    assert doc["cli"]["init"]["apiKeySource"] == "apiKeyHelper" and "Bash" not in doc["cli"]["init"]["tools"]

    api = run.api_calls()
    assert all(c["api_key"] == KEY for c in api)                       # in-process, not from the env
    assert [c["model"] for c in api if c["ping"]] == ["claude-opus-4-1-20250805"] * 2   # preflight, validate
    assert not any(c["model"] == "claude-3-5-haiku-20241022" for c in api)
    assert sorted(c["categories"][0] for c in api if not c["ping"]) == ["command_injection", "sensitive_data_logging"]
    assert doc["api_usage"]["claude-opus-4-1-20250805"]["input_tokens"] == 100 * len(api)
    _assert_key_only_in_the_key_file(run, result)


