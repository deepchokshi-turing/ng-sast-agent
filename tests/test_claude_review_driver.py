    for name in ("CLAUDE_CODE_PROVIDER_MANAGED_BY_HOST", "CLAUDE_CODE_USE_BEDROCK", "ANTHROPIC_MODEL",
                 "ANTHROPIC_BASE_URL", "CLAUDE_CONFIG_DIR", "CLAUDE_MODEL", "CLAUDECODE", "NODE_OPTIONS", "SECRET_X"):
        monkeypatch.setenv(name, "1")
    monkeypatch.setenv("LC_ALL", "C.UTF-8")
    monkeypatch.setenv("HTTPS_PROXY", "http://proxy:3128")
    env = driver.cli_environment("/h", KEY, "api_key_helper", "/opt/bin")
    assert not [n for n in env if n.startswith(("ANTHROPIC_", "CLAUDE_MODEL", "CLAUDECODE", "CLAUDE_CONFIG"))]
    assert sorted(n for n in env if n.startswith("CLAUDE_CODE_")) == ["CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC"]
    assert "NODE_OPTIONS" not in env and "SECRET_X" not in env
    assert env["LC_ALL"] == "C.UTF-8" and env["HTTPS_PROXY"] == "http://proxy:3128"


